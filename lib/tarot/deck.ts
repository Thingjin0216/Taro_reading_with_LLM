function pad(value: number): string {
  return String(value).padStart(2, "0");
}

const majorCards: TarotCard[] = MAJOR.map(([nameKo, nameEn, upright, reversed], index) => {
  const id = `major-${pad(index)}`;
  return {
    id,
    nameKo,
    nameEn,
    arcana: "major",
    number: index,
    keywordsUpright: upright,
    keywordsReversed: reversed,
    image: `/cards/${id}.webp`,
  };
});

const minorCards: TarotCard[] = MINOR_SUITS.flatMap((suit) =>
  MINOR[suit].map(([upright, reversed], index) => {
    const number = index + 1;
    const id = `${suit}-${pad(number)}`;
    return {
      id,
      nameKo: `${SUIT_KO[suit]} ${RANK_KO[index]}`,
      nameEn: `${RANK_EN[index]} of ${SUIT_EN[suit]}`,
      arcana: "minor" as const,
      suit,
      number,
      keywordsUpright: upright,
      keywordsReversed: reversed,
      image: `/cards/${id}.webp`,
    };
  }),
);

export const DECK: TarotCard[] = [...majorCards, ...minorCards];

const BY_ID = new Map(DECK.map((card) => [card.id, card]));

export function getCard(id: string): TarotCard | undefined {
  return BY_ID.get(id);
}
